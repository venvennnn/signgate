def agreement_values(manifest: IntentManifest) -> dict[str, str]:
    value = manifest["commercial_terms"]["contract_value"]
    money = f"{value['currency']} {value['amount']:,}"
    sow = "Statement of Work" in manifest["required_attachments"]
    renewal = (
        f"This Agreement automatically renews for successive {manifest['commercial_terms']['term_months']}-month periods unless either party provides {manifest['legal_terms']['termination_notice_days']} days written notice."
        if manifest["legal_terms"]["auto_renewal"]
        else "This Agreement does not automatically renew. Any extension requires a new written instrument signed by both parties."
    )
    guarantee = (
        "The undersigned individual personally guarantees the Customer's obligations under this Agreement."
        if manifest["legal_terms"]["personal_guarantee"]
        else "Neither party provides a personal guarantee. No personal liability is assumed by any director, officer, or employee."
    )
    exclusive = (
        "Customer hereby appoints Vendor as its exclusive provider of the Services."
        if manifest["legal_terms"]["exclusivity"]
        else "This Agreement does not grant exclusivity. Customer may obtain similar services from other vendors."
    )
    fields = "\n".join(
        [
            "--- SIGNGATE INTENT FIELDS ---",
            f"document_type: {manifest['document_type']}",
            f"customer: {manifest['parties']['customer']}",
            f"vendor: {manifest['parties']['vendor']}",
            f"contract_value_amount: {value['amount']}",
            f"contract_value_currency: {value['currency']}",
            f"term_months: {manifest['commercial_terms']['term_months']}",
            f"payment_terms_days: {manifest['commercial_terms']['payment_terms_days']}",
            f"termination_notice_days: {manifest['legal_terms']['termination_notice_days']}",
            f"auto_renewal: {str(manifest['legal_terms']['auto_renewal']).lower()}",
            f"personal_guarantee: {str(manifest['legal_terms']['personal_guarantee']).lower()}",
            f"exclusivity: {str(manifest['legal_terms']['exclusivity']).lower()}",
            f"governing_law: {manifest['legal_terms']['governing_law']}",
            f"attachments: {', '.join(manifest['required_attachments'])}",
            f"bank_account: {manifest['bank_details']['account_number'] or ''}",
            f"bank_account_name: {manifest['bank_details']['account_name'] or ''}",
            f"bank_name: {manifest['bank_details']['bank_name'] or ''}",
            "--- END SIGNGATE INTENT FIELDS ---",
        ]
    )
    return {
        "title": manifest["title"].upper(),
        "customer": manifest["parties"]["customer"],
        "vendor": manifest["parties"]["vendor"],
        "contract_value": money,
        "term_months": str(manifest["commercial_terms"]["term_months"]),
        "payment_terms_days": str(manifest["commercial_terms"]["payment_terms_days"]),
        "termination_notice_days": str(manifest["legal_terms"]["termination_notice_days"]),
        "renewal_clause": renewal,
        "governing_law": manifest["legal_terms"]["governing_law"],
        "guarantee_clause": guarantee,
        "exclusivity_clause": exclusive,
        "account_name": manifest["bank_details"]["account_name"] or "—",
        "bank_name": manifest["bank_details"]["bank_name"] or "—",
        "bank_account": manifest["bank_details"]["account_number"] or "—",
        "sow_block": (
            "Schedule A — Statement of Work. This Statement of Work is attached to and forms part of the Agreement."
            if sow
            else ""
        ),
        "signer_name": manifest["signer"]["name"],
        "fields_block": fields,
    }


def cover_sheet_values(manifest: IntentManifest, verified_at: str) -> dict[str, str]:
    value = manifest["commercial_terms"]["contract_value"]
    sow = "Statement of Work" in manifest["required_attachments"]
    return {
        "gate_status": "OPEN",
        "manifest_hash": fingerprint(checksum_from_manifest(manifest)),
        "verified_at": verified_at,
        "contract_value": f"{value['currency']} {value['amount']:,}",
        "term_label": f"{manifest['commercial_terms']['term_months']} months",
        "termination_label": f"{manifest['legal_terms']['termination_notice_days']}-day termination",
        "renewal_label": "No automatic renewal" if not manifest["legal_terms"]["auto_renewal"] else "Automatic renewal",
        "sow_label": "Statement of Work required" if sow else "No Statement of Work",
        "customer": manifest["parties"]["customer"],
        "vendor": manifest["parties"]["vendor"],
    }
